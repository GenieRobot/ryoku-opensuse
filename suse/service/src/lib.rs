pub enum Request {
    Discover,
    GetOperation { operation_id: OperationId },
    Start { action: ManagedAction },
}

/// Only named product operations can cross the service boundary.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
